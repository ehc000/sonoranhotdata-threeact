
"""
Defines API endpoints for the personalized lesson-generation workflow.

Purpose:
    Expose story concept generation through FastAPI so the teacher
    frontend can request personalized story ideas for a student.

    Validates incoming requests and delegates story generation
    to backend/lesson_generation/service.py.

Directed and reviewed by: Edenna Chen
Generated by: ChatGPT (OpenAI), GPT-6, 2026-11-05
Human edits: modified to add lesson pacing function (generated but added separately) for lesson structuring (time, pace, etc.)
External sources: None

Notes:
    - Uses the existing FastAPI application.
    - Provides POST /api/lessons/story-concepts.
    - Validates student ID, learning objective, and question count.
    - Does not modify existing educator-loop endpoints.
    - FastAPI routes for lesson story generation."""

from fastapi import APIRouter, HTTPException
from pydantic import BaseModel, Field

from backend.lesson_generation.service import generate_story_concepts

router = APIRouter(prefix="/api/lessons", tags=["lessons"])


class LessonPacing(BaseModel):
    """
    Teacher-configurable lesson pacing.

    Integration directed by: Edenna Chen
    Generated by: ChatGPT (OpenAI), GPT-6, 2026-11-05

    These are planning preferences, not student attention measurements.
    """

    target_minutes: int | None = Field(default=20, ge=1, le=120)
    questions_per_chunk: int = Field(default=2, ge=1, le=10)
    offer_breaks: bool = True
    break_minutes: int = Field(default=3, ge=1, le=15)
    pacing_mode: str = Field(
        default="student",
        pattern="^(student|teacher)$",
    )

class StoryConceptRequest(BaseModel):
    student_id: str = Field(min_length=1)
    objective: str = Field(min_length=1)
    question_count: int = Field(default=5, ge=1, le=20)
    teacher_instructions: str = ""
    pacing: LessonPacing = Field(default_factory=LessonPacing)


@router.post("/story-concepts")

@router.post("/story-concepts")
def create_story_concepts(request: StoryConceptRequest):
    try:
        result = generate_story_concepts(
            student_id=request.student_id,
            objective=request.objective,
            question_count=request.question_count,
            teacher_instructions=request.teacher_instructions,
        )

        # Keep teacher-selected pacing settings with the generated
        # concepts. This does not change the story-generation prompt.
        return {
            **result,
            "pacing": request.pacing.model_dump(),
        }

    except ValueError as exc:
        raise HTTPException(status_code=404, detail=str(exc))
    except RuntimeError as exc:
        raise HTTPException(status_code=502, detail=str(exc))


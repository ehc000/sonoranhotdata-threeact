def build_visual_theme(concept: dict) -> dict:
    return {
        "style": "cozy_pixel_art",
        "setting": concept["title"],
        "description": concept["premise"],
        "character_consistency": True,
        "background_consistency": True,
        "scene_changes": "small_progressive_changes",
        "finale_animation": "gentle_bounce",
        "reduced_motion_supported": True,
    }

def generate_story_concepts(
    student_id: str,
    objective: str,
    question_count: int,
    teacher_instructions: str = "",
):
    context = load_student_context(student_id)
    if context is None:
        raise ValueError("Student not found")

    request = {
        "student_context": context,
        "learning_objective": objective,
        "question_count": question_count,
        "teacher_instructions": teacher_instructions,
    }

    # Fixed mock output lets the frontend be tested without an API key.
    mock_reply = {
        "concepts": [
            {
                "id": "concept_1",
                "title": "Robot Rescue",
                "premise": "A robot needs help repairing its workshop.",
                "story_goal": "Restore the robot and open the workshop.",
                "learning_connection": "Math challenges guide each repair.",
            },
            {
                "id": "concept_2",
                "title": "Mountain Expedition",
                "premise": "A team must reach a remote research station.",
                "story_goal": "Navigate the route and deliver supplies.",
                "learning_connection": "Math helps plan each stage.",
            },
            {
                "id": "concept_3",
                "title": "Mystery Museum",
                "premise": "An exhibit has been mysteriously locked.",
                "story_goal": "Solve clues to reopen the exhibit.",
                "learning_connection": "Math challenges reveal the clues.",
            },
        ]
    }

    result = llm_query.chat_json(
        [
            {"role": "system", "content": load_story_concept_prompt()},
            {
                "role": "user",
                "content": json.dumps(request, ensure_ascii=False),
            },
        ],
        mock_reply=mock_reply,
        temperature=0.5,
        prompt_id="lesson_story_concepts",
    )

    if not isinstance(result, dict):
        raise RuntimeError("LLM returned invalid JSON")

    concepts = result.get("concepts")
    if not isinstance(concepts, list) or len(concepts) != 3:
        raise RuntimeError("Expected exactly three story concepts")

    required = {"id", "title", "premise", "story_goal", "learning_connection"}

    # AI-ASSISTED UPDATE (2026-11-05)
    # Identify which LLM-generated concept field failed validation.
    # Preserve the existing validation requirements.

    for index, concept in enumerate(concepts):
        if not isinstance(concept, dict):
            raise RuntimeError(
                f"Concept {index + 1} is not a JSON object"
            )

        for key in required:
            value = concept.get(key)

            if not isinstance(value, str) or not value.strip():
                raise RuntimeError(
                    f"Concept {index + 1} has invalid field '{key}': "
                    f"{value!r}"
                )

    if len({concept["id"] for concept in concepts}) != 3:
        raise RuntimeError("Story concept IDs must be unique")

    # AI-assisted addition:
    # Attach a consistent pixel-art visual specification to each
    # personalized story concept without changing the original fields.
    for concept in concepts:
        concept["visual_theme"] = build_visual_theme(concept)

    return {
        "student_id": student_id,
        "objective": objective,
        "question_count": question_count,
        "concepts": concepts,
        "llm_mode": llm_query.mode(),
}

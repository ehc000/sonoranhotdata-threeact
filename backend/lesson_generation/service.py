import json

from backend.database.connection import get_connection
from backend.database.profiles import get_profile
from backend import llm_query
from backend.lesson_generation.prompts import load_story_concept_prompt


def load_student_context(student_id: str):
    """Load real student data, without modifying it."""
    with get_connection() as conn:
        student = conn.execute(
            "SELECT id, name, grade_level FROM students WHERE id = ?",
            (student_id,),
        ).fetchone()

        if student is None:
            return None

        # AI-ASSISTED UPDATE (2026-11-05), ChatGPT
        # Include pacing preferences in personalized story context. 
        # Load student preferences, including break duration.
        preferences = conn.execute(
            """
            SELECT interests,
                   interests_text,
                   learning_preferences_text,
                   content_format,
                   sensory_sensitive,
                   help_mode,
                   break_minutes
            FROM student_preferences
            WHERE student_id = ?
            """,
            (student_id,),
        ).fetchone()

    # AI-ASSISTED UPDATE (2026-11-05)
    # Convert stored JSON interests into a structured list.
    preferences_data = dict(preferences) if preferences else {}

    try:
        preferences_data["interests"] = json.loads(
            preferences_data.get("interests") or "[]"
        )
    except (json.JSONDecodeError, TypeError):
        preferences_data["interests"] = []

    return {
        "student": dict(student),
        "preferences": preferences_data,
        "profile": get_profile(student_id),
    }


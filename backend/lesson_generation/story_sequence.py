
"""
Generates a connected narrative around approved lesson questions.

Purpose:
    Use the shared LLM wrapper to create an introduction,
    one story segment per question, and a conclusion.

    Preserve approved academic questions by generating only
    narrative text, never replacement question content.

Directed and reviewed by: Edenna Chen
Generated by: ChatGPT (OpenAI), GPT-6, 2026-11-05
Human edits: None yet
External sources: None

Notes:
    - Uses the shared LLM wrapper.
    - Supports offline mock testing.
    - Validates question IDs and their order.
    - Does not modify question text or answers.
"""

import json

from backend import llm_query
from backend.lesson_generation.prompts import load_story_sequence_prompt


def generate_story_sequence(objective, story_concept, questions, pacing):
    """Generate narrative text for an ordered set of approved questions."""

    if not questions:
        raise ValueError("At least one approved question is required.")

    question_ids = [question["id"] for question in questions]

    if len(question_ids) != len(set(question_ids)):
        raise ValueError("Question IDs must be unique.")

    # Send question text as context, but never use the model to replace it.
    request = {
        "objective": objective,
        "story_concept": story_concept,
        "questions": [
            {
                "id": question["id"],
                "text": question.get("text") or question.get("original"),
            }
            for question in questions
        ],
        "pacing": pacing,
    }

    # Deterministic output for offline testing.
    mock_reply = {
        "introduction": (
            f"Welcome to {story_concept['title']}! "
            "Your adventure is about to begin."
        ),
        "segments": [
            {
                "question_id": question_id,
                "narrative": (
                    f"Complete challenge {index} to advance the mission."
                ),
            }
            for index, question_id in enumerate(question_ids, start=1)
        ],
        "conclusion": (
            "You have reached the end of the mission. "
            "Review your progress with your teacher."
        ),
    }

    result = llm_query.chat_json(
        [
            {
                "role": "system",
                "content": load_story_sequence_prompt(),
            },
            {
                "role": "user",
                "content": json.dumps(request, ensure_ascii=False),
            },
        ],
        mock_reply=mock_reply,
        temperature=0.6,
        prompt_id="lesson_story_sequence",
    )

    if not isinstance(result, dict):
        raise RuntimeError("Story sequence must be a JSON object.")

    segments = result.get("segments")

    if not isinstance(segments, list):
        raise RuntimeError("Story segments must be a list.")

    returned_ids = [
        segment.get("question_id")
        if isinstance(segment, dict) else None
        for segment in segments
    ]

    if returned_ids != question_ids:
        raise RuntimeError(
            "Story segment IDs do not match the approved question order."
        )

    if not isinstance(result.get("introduction"), str) or not result["introduction"].strip():
        raise RuntimeError("Missing story introduction.")

    if not isinstance(result.get("conclusion"), str) or not result["conclusion"].strip():
        raise RuntimeError("Missing story conclusion.")

    for segment in segments:
        if (
            not isinstance(segment.get("narrative"), str)
            or not segment["narrative"].strip()
        ):
            raise RuntimeError("Invalid narrative segment.")

    return {
        "introduction": result["introduction"],
        "segments": segments,
        "conclusion": result["conclusion"],
        "llm_mode": llm_query.mode(),
    }

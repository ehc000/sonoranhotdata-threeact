
"""
Assembles a teacher-approved lesson into structured JSON.

Purpose:
    Combine a selected story concept, approved academic questions,
    and teacher-configured pacing into a student lesson.

    Preserve question IDs and approved question text. Do not
    generate new mathematics or calculate competency scores.

Directed and reviewed by: Edenna Chen
Generated by: ChatGPT (OpenAI), GPT-6, 2026-11-05
Human edits: Integrated generated code for story sequencing functionality
External sources: None
"""

import uuid
from backend.lesson_generation.story_sequence import generate_story_sequence


def assemble_lesson(student_id, objective, story_concept, questions, pacing):
    """Build a structured lesson without making an LLM call."""

    if not questions:
        raise ValueError("Cannot assemble a lesson without questions.")

    if not story_concept or not story_concept.get("title"):
        raise ValueError("A selected story concept is required.")

    chunk_size = int(pacing.get("questions_per_chunk", 2))
    if chunk_size < 1:
        raise ValueError("questions_per_chunk must be positive.")

    # Never expose the answer key in the student-facing question blocks.
    blocks = []
    for index, question in enumerate(questions):
        if question.get("status") == "rejected":
            continue

        question_id = question["id"]
        question_text = question.get("text") or question.get("original")

        if not question_text:
            raise ValueError(f"Question {question_id} has no text.")

        blocks.append({
            "type": "question",
            "question_id": question_id,
            "competency": question["competency"],
            "difficulty": question["difficulty"],
            "text": question_text,
            "sequence": index + 1,
        })

    if not blocks:
        raise ValueError("No approved questions available.")


    # INSERTED GENERATED CODE TO ADD STORY SEQUENCING FUNCTIONALITY.
    # Generate one connected storyline for the approved questions.
    # The LLM only supplies narrative text, never replacement questions.
    story_sequence = generate_story_sequence(
        objective=objective,
        story_concept=story_concept,
        questions=[
            question
            for question in questions
            if question.get("status") != "rejected"
        ],
        pacing=pacing,
    )

    # Match each narrative segment to its original question ID.
    narrative_by_id = {
        segment["question_id"]: segment["narrative"]
        for segment in story_sequence["segments"]
    }

    for block in blocks:
        block["narrative"] = narrative_by_id[block["question_id"]]


    # Break the questions into manageable activity groups.
    chunks = [
        blocks[i:i + chunk_size]
        for i in range(0, len(blocks), chunk_size)
    ]

    activities = []
    for index, chunk in enumerate(chunks):
        activities.append({
            "type": "activity",
            "activity_number": index + 1,
            "questions": chunk,
            "offer_break_after": (
                bool(pacing.get("offer_breaks", True))
                and index < len(chunks) - 1
            ),
        })

    return {
        "lesson_id": uuid.uuid4().hex,
        "student_id": student_id,
        "objective": objective,
        "story": story_concept,
        "pacing": pacing,
        # EDITED ORIGINAL DICTIONARY TO INTEGRATE STORY SEQUENCING PIECES, SEE BELOW.
        "introduction": story_sequence["introduction"],
        "activities": activities,
        "conclusion": story_sequence["conclusion"],
        "llm_mode": story_sequence["llm_mode"],
    }

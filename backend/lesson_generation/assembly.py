"""Assemble teacher-approved academic questions into a mission-based lesson.

Purpose: Preserve approved questions, generate a coherent mission roadmap,
and attach existing story sequence, help, and scene descriptions.
Original implementation: Team lesson assembly module.
Directed and reviewed by: Edenna Chen
AI-assisted modifications: ChatGPT (OpenAI), GPT-6, 2026-11-05
Human edits: Pending review
External sources: None

This creates a teacher preview only. It does not assign or persist a lesson.
"""

import uuid

from backend.lesson_generation.mission_planner import generate_mission_plan
from backend.lesson_generation.story_sequence import generate_story_sequence


# ------------------------------------------------------------
# AI-ASSISTED MODIFICATION: assemble_lesson()
# Purpose: Generate a mission roadmap and associate each milestone
# with its original approved academic question, without rewriting it.
# Directed by: Edenna Chen
# Generated by: ChatGPT (OpenAI), GPT-6, 2026-11-05
# ------------------------------------------------------------
def assemble_lesson(student_id, objective, story_concept, questions, pacing):
    """Return a teacher-reviewable lesson, preserving the existing API signature."""
    if not questions:
        raise ValueError("Cannot assemble a lesson without questions.")
    if not isinstance(story_concept, dict) or not story_concept.get("title"):
        raise ValueError("A selected story concept is required.")

    pacing = pacing or {}
    chunk_size = int(pacing.get("questions_per_chunk", 2))
    if chunk_size < 1:
        raise ValueError("questions_per_chunk must be positive.")

    approved_questions = [q for q in questions if q.get("status") != "rejected"]
    if not approved_questions:
        raise ValueError("No approved questions available.")

    blocks = []
    for index, question in enumerate(approved_questions, start=1):
        question_id = str(question["id"])
        question_text = question.get("text") or question.get("original")
        if not question_text:
            raise ValueError(f"Question {question_id} has no text.")
        blocks.append({
            "type": "question",
            "question_id": question_id,
            "competency": question["competency"],
            "difficulty": question["difficulty"],
            "text": question_text,
            "sequence": index,
        })

    # ------------------------------------------------------------
    # AI-ASSISTED ADDITION: Plan the mission before story sequencing.
    # Purpose: Define one overall goal and a task for every question.
    # Directed by: Edenna Chen
    # Generated by: ChatGPT (OpenAI), GPT-6, 2026-11-05
    # ------------------------------------------------------------
    # AI-assisted: use teacher-selected language level from the existing pacing payload.
    # Preserve the endpoint's function signature for compatibility.
    story_complexity = pacing.get("story_complexity", "simple")
    if story_complexity not in {"simple", "moderate", "rich"}:
        raise ValueError("Invalid story complexity.")
    mission_plan = generate_mission_plan(
        presentation={"story_complexity": story_complexity},
        objective=objective,
        story_concept=story_concept,
        questions=approved_questions,
    )

    # AI-ASSISTED MODIFICATION: feed the same roadmap to story generation.
    # Purpose: Keep story scenes and academic challenges on one mission path.
    # Directed by: Edenna Chen; Generated by: ChatGPT (OpenAI), GPT-6, 2026-11-05.
    story_sequence = generate_story_sequence(
        objective=objective,
        story_concept=story_concept,
        questions=approved_questions,
        pacing=pacing,
        story_complexity=mission_plan["presentation"]["story_complexity"],
        mission_plan={
            "mission": mission_plan["mission"],
            "milestones": mission_plan["milestones"],
            "presentation": mission_plan["presentation"],
        },
    )

    segments_by_id = {
        str(segment["question_id"]): segment
        for segment in story_sequence["segments"]
    }
    milestones_by_id = {
        str(milestone["question_id"]): milestone
        for milestone in mission_plan["milestones"]
    }

    # ------------------------------------------------------------
    # AI-ASSISTED ADDITION: Attach mission progress to question blocks.
    # Purpose: Let the future student player reveal progress only after
    # the application verifies an answer; never pre-mark tasks complete.
    # Directed by: Edenna Chen
    # Generated by: ChatGPT (OpenAI), GPT-6, 2026-11-05
    # ------------------------------------------------------------
    for block in blocks:
        qid = block["question_id"]
        segment = segments_by_id[qid]
        milestone = milestones_by_id[qid]
        block.update({
            "mission_task_id": milestone["id"],
            "mission_task_title": milestone["title"],
            "mission_task_purpose": milestone["purpose"],
            "mission_unlocks": milestone["unlocks"],
            "narrative": segment["narrative"],  # Legacy preview compatibility.
            "story_dialogue": segment["story_dialogue"],
            "challenge_transition": segment["challenge_transition"],
            "optional_reminder": segment["optional_reminder"],
            "optional_walkthrough": segment["optional_walkthrough"],
            "visual_prompt": milestone["before_visual_prompt"],
            "before_visual_prompt": milestone["before_visual_prompt"],
            "after_visual_prompt": milestone["after_visual_prompt"],
            "story_bridge": segment.get("story_bridge", ""),
            "success_event": segment.get("success_event", ""),
        })

    chunks = [blocks[i:i + chunk_size] for i in range(0, len(blocks), chunk_size)]
    activities = [
        {
            "type": "activity",
            "activity_number": index + 1,
            "questions": chunk,
            "offer_break_after": (
                bool(pacing.get("offer_breaks", True))
                and index < len(chunks) - 1
            ),
        }
        for index, chunk in enumerate(chunks)
    ]

    warnings = [
        warning for warning in (
            mission_plan.get("alignment_warning"),
            story_sequence.get("alignment_warning"),
        ) if warning
    ]

    return {
        "lesson_id": uuid.uuid4().hex,
        "student_id": student_id,
        "objective": objective,
        "story": story_concept,
        "pacing": pacing,  # Retained for existing frontend/API compatibility.
        "mission": mission_plan["mission"],
        "milestones": mission_plan["milestones"],
        "presentation": mission_plan["presentation"],
        "story_complexity": story_sequence["story_complexity"],
        "alignment_warning": " | ".join(warnings) if warnings else None,
        "introduction": story_sequence["introduction"],
        "introduction_visual_prompt": story_sequence["introduction_visual_prompt"],
        "refresher": story_sequence["refresher"],
        "activities": activities,
        "conclusion": story_sequence["conclusion"],
        "conclusion_visual_prompt": story_sequence["conclusion_visual_prompt"],
        "finale_animation": story_sequence["finale_animation"],
        "llm_mode": story_sequence["llm_mode"],
        "mission_llm_mode": mission_plan["llm_mode"],
    }

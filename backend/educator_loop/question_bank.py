def _frac(n, d):
    """Fraction as a canonical answer string ('3/4', or '2' when whole)."""
    f = Fraction(n, d)
    return str(f.numerator) if f.denominator == 1 else f"{f.numerator}/{f.denominator}"


def _money(x):
    return f"{x:.2f}".rstrip("0").rstrip(".")



def build_bank(seed=SEED, instances=INSTANCES_PER_TEMPLATE):
    rng = random.Random(seed)
    bank, seen = [], set()
    for cid, templates in TEMPLATES.items():
        for ti, template in enumerate(templates):
            made = 0
            while made < instances:
                prompt, answer, difficulty = template(rng)
                if prompt in seen:
                    continue
                seen.add(prompt)
                bank.append(
                    {
                        "id": f"{cid[:2]}{ti + 1}-{made + 1}",
                        "competency": cid,
                        "difficulty": difficulty,
                        "template": template.__name__,
                        "prompt": prompt,
                        "answer": answer,
                        "rewrap": "framing" if template.__name__ in FRAMING_ONLY else "full",
                    }
                )
                made += 1
    return bank


QUESTIONS = build_bank()
BY_ID = {q["id"]: q for q in QUESTIONS}


def questions_for(competency_id):
    """Every question tagged with the given competency, easiest first."""
    matches = [q for q in QUESTIONS if q["competency"] == competency_id]
    return sorted(matches, key=lambda q: (q["difficulty"], q["id"]))



def t_fr_sub(r):
    a, b = r.choice([3, 4, 5, 6]), r.choice([2, 3, 4])
    n1, n2 = r.randint(1, a - 1), r.randint(1, b - 1)
    f = Fraction(n1, a) - Fraction(n2, b)
    if f <= 0:
        f, n1, n2 = -f, n2, n1
        a, b = b, a
    return (
        f"What is {n1}/{a} - {n2}/{b}? Give your answer as a fraction in simplest form.",
        _frac(f.numerator, f.denominator),
        2,
    )



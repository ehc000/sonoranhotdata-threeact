import re
from pathlib import Path

PROMPTS_DIR = Path(__file__).resolve().parents[2] / "prompts"
_FRONTMATTER = re.compile(r"^---\n.*?\n---\n", re.S)
_SECTION = re.compile(r"^# (system|user)\n", re.M)


def load(prompt_id):
    """Return {"system": str, "user": str} for prompts/<prompt_id>.md (metadata stripped)."""
    text = (PROMPTS_DIR / f"{prompt_id}.md").read_text(encoding="utf-8")
    body = _FRONTMATTER.sub("", text, count=1)
    parts = _SECTION.split(body)
    # parts: ["", "system", <text>, "user", <text>]
    sections = {parts[i]: parts[i + 1].strip() for i in range(1, len(parts) - 1, 2)}
    if "system" not in sections:
        raise ValueError(f"prompt {prompt_id} has no '# system' section")
    return sections


def fill(template, **variables):
    """Replace every {{name}} in the template. Unknown names are left in place so the gap is visible."""

    def sub(m):
        name = m.group(1)
        return str(variables[name]) if name in variables else m.group(0)

    return re.sub(r"\{\{(\w+)\}\}", sub, template)


def messages(prompt_id, **variables):
    """Build the [system, user] message list for a prompt."""
    p = load(prompt_id)
    out = [{"role": "system", "content": fill(p["system"], **variables)}]
    if p.get("user"):
        out.append({"role": "user", "content": fill(p["user"], **variables)})
    return out

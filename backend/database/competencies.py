from backend.database.connection import get_connection


def get_competency(student_id: str, competency: str):
    """Return one student's progress for a specific skill."""
    with get_connection() as conn:
        row = conn.execute(
            """
            SELECT student_id, competency, mastery_score,
                   status, updated_at
            FROM competency_progress
            WHERE student_id = ? AND competency = ?
            """,
            (student_id, competency),
        ).fetchone()

    return dict(row) if row else None


def get_student_competencies(student_id: str):
    """Return all stored competency records for a student."""
    with get_connection() as conn:
        rows = conn.execute(
            """
            SELECT student_id, competency, mastery_score,
                   status, updated_at
            FROM competency_progress
            WHERE student_id = ?
            ORDER BY competency
            """,
            (student_id,),
        ).fetchall()

    return [dict(row) for row in rows]


def save_competency(
    student_id: str,
    competency: str,
    mastery_score: float | None,
    status: str,
):
    """
    Insert or update a competency record.

    This function stores a supplied score. It does not decide
    how mastery should be calculated.
    """
    if mastery_score is not None and not 0 <= mastery_score <= 1:
        raise ValueError("mastery_score must be between 0 and 1.")

    with get_connection() as conn:
        conn.execute(
            """
            INSERT INTO competency_progress (
                student_id, competency, mastery_score,
                status, updated_at
            )
            VALUES (?, ?, ?, ?, CURRENT_TIMESTAMP)
            ON CONFLICT(student_id, competency)
            DO UPDATE SET
                mastery_score = excluded.mastery_score,
                status = excluded.status,
                updated_at = CURRENT_TIMESTAMP
            """,
            (student_id, competency, mastery_score, status),
        )

    return get_competency(student_id, competency)

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LOG = ROOT / "logs" / "model_calls.jsonl"
PROMPTS = {p.stem for p in (ROOT / "prompts").glob("*.md")}


def main():
    if not LOG.exists():
        print("no log at", LOG, "- run the app with PROMPT_LOG=1 first")
        return 2
    used, missing, unnamed = set(), set(), 0
    for line in LOG.read_text(encoding="utf-8").splitlines():
        rec = json.loads(line)
        pid = rec.get("prompt_id")
        if not pid:
            unnamed += 1
        elif pid in PROMPTS:
            used.add(pid)
        else:
            missing.add(pid)
    print(f"prompt files: {sorted(PROMPTS)}\nused in log: {sorted(used)}\nnever logged: {sorted(PROMPTS - used)}")
    if missing or unnamed:
        print(f"FAIL: logged prompts without a file: {sorted(missing)}; calls with no prompt_id: {unnamed}")
        return 1
    print("OK: every logged call maps to a prompt file")
    return 0


if __name__ == "__main__":
    sys.exit(main())

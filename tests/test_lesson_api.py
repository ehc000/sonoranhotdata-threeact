import os

# Enable mock responses before importing the application.
os.environ["MOCK_LLM"] = "1"

from fastapi.testclient import TestClient
from backend.main import app


client = TestClient(app)

payload = {
    "student_id": "test-student",
    "objective": "Solve linear equations",
    "story_concept": {
        "title": "Minecraft Fortress Quest",
        "premise": "Build a fortress by solving equations.",
        "story_goal": "Complete the fortress.",
    },
    "questions": [
        {
            "id": "q1",
            "competency": "linear_equations",
            "difficulty": 1,
            "text": "Solve x + 2 = 5.",
            "status": "ok",
        },
        {
            "id": "q2",
            "competency": "linear_equations",
            "difficulty": 1,
            "text": "Solve x + 3 = 7.",
            "status": "ok",
        },
    ],
    "pacing": {
        "target_minutes": 20,
        "questions_per_chunk": 1,
        "offer_breaks": True,
        "break_minutes": 3,
        "pacing_mode": "student",
    },
}


def test_teacher_approval_required():
    response = client.post(
        "/api/lessons/assemble",
        json={**payload, "teacher_approved": False},
    )
    assert response.status_code == 403


def test_approved_lesson_assembly():
    response = client.post(
        "/api/lessons/assemble",
        json={**payload, "teacher_approved": True},
    )

    assert response.status_code == 200, response.text

    lesson = response.json()

    assert len(lesson["activities"]) == 2
    assert lesson["activities"][0]["questions"][0]["question_id"] == "q1"
    assert lesson["activities"][1]["questions"][0]["question_id"] == "q2"

    assert lesson["activities"][0]["questions"][0]["text"] == "Solve x + 2 = 5."
    assert lesson["activities"][1]["questions"][0]["text"] == "Solve x + 3 = 7."

    assert lesson["activities"][0]["questions"][0]["narrative"]
    assert lesson["activities"][1]["questions"][0]["narrative"]

    assert lesson["activities"][0]["offer_break_after"] is True
    assert lesson["activities"][1]["offer_break_after"] is False

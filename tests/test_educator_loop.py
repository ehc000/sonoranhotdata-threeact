def test_rewrap_guards():
    q = {"prompt": "What is -15 + 4?", "rewrap": "framing"}
    missing, note = engine.check_rewrap(
        q, "A cat was 15 degrees below normal and regained 4 degrees. What is the change?"
    )
    assert missing == ["-15"] and note.startswith("expression not kept verbatim")
    assert engine.check_rewrap(q, "On a cold ledge: what is -15 + 4?") == ([], None)
    assert engine.check_numbers("ratio 3:7 of syrup", "3 to 7 syrup") == []


def test_full_loop_and_blocker_detection():
    prep = _prep("Ari", "dinosaurs", ["integers", "fractions", "ratios"], "make one of each hard")
    assert prep["questions"] and all(q["text"] for q in prep["questions"])
    q0, q1 = prep["questions"][0], prep["questions"][1]
    edited = c.post(f"/api/preps/{prep['id']}/questions/{q0['id']}/edit", json={"text": "no numbers here"}).json()
    assert edited["flagged"]
    c.post(f"/api/preps/{prep['id']}/questions/{q0['id']}/edit", json={"text": q0["text"]})
    c.post(f"/api/preps/{prep['id']}/questions/{q1['id']}/reject", json={"rejected": True})
    s = c.post(f"/api/preps/{prep['id']}/approve").json()
    assert len(s["questions"]) == len(prep["questions"]) - 1
    assert "answer" not in s["questions"][0] and "original" not in s["questions"][0]
    for q in s["questions"]:
        given = BY_ID[q["id"]]["answer"] if q["competency"] == "integers" else "0"
        c.post(f"/api/sessions/{s['id']}/questions/{q['id']}/answer", json={"answer": given})
    rev = c.post(f"/api/sessions/{s['id']}/finish").json()
    assert rev["stats"]["integers"]["status"] == "mastered"
    assert rev["stats"]["fractions"]["status"] == "struggling"
    assert any(b["blocker"] == "fractions" and b["blocks"] == "ratios" for b in rev["blockers"])
    prof = c.post(f"/api/sessions/{s['id']}/approve", json={"overrides": {}, "note": "Reteach fractions."}).json()
    assert prof["competencies"]["integers"]["status"] == "mastered" and prof["interest"] == "dinosaurs"


def test_profile_informs_next_prep():
    prep = _prep("Ari", "", ["integers", "proportions"])
    assert prep["interest"] == "dinosaurs"  # reused from the profile
    levels = {q["difficulty"] for q in prep["questions"] if q["competency"] == "integers"}
    assert 1 not in levels  # mastered -> easiest skipped


def test_help_is_capped():
    prep = _prep("Bo", "space", ["integers"], per=1)
    s = c.post(f"/api/preps/{prep['id']}/approve").json()
    qid = s["questions"][0]["id"]
    replies = [
        c.post(f"/api/sessions/{s['id']}/questions/{qid}/help", json={"message": "hint?"}).json()
        for _ in range(engine.HELP_CAP + 1)
    ]
    assert replies[-2]["capped"] and replies[-1]["reply"] is None

from backend.lesson_generation.assembly import assemble_lesson


def test_lesson_assembly():
    questions = []

    for i in range(1, 6):
        questions.append({
            "id": f"q{i}",
            "competency": "linear_equations",
            "difficulty": 1,
            "text": f"Solve x + {i} = 10.",
            "status": "ok",
        })

    lesson = assemble_lesson(
        student_id="test-student",
        objective="Solve linear equations",
        story_concept={
            "title": "Minecraft Fortress Quest",
            "premise": "Build a fortress by solving equations.",
            "story_goal": "Complete the fortress.",
        },
        questions=questions,
        pacing={
            "target_minutes": 20,
            "questions_per_chunk": 2,
            "offer_breaks": True,
            "break_minutes": 3,
            "pacing_mode": "student",
        },
    )

    assert len(lesson["activities"]) == 3

    sizes = [
        len(activity["questions"])
        for activity in lesson["activities"]
    ]

    assert sizes == [2, 2, 1]
    assert lesson["activities"][-1]["offer_break_after"] is False

    print("PASS: Lesson assembly and pacing work")
